// Pull the physics and the element data the website needs out of the app
// itself, so the site never carries a second copy that could drift. The app's
// Parts 1 to 7 (constants, hydrogenic functions, the 118 elements, electron
// configurations, Slater's rules, the nuclear formulas) and the table's own
// data are copied verbatim; the binding curve is computed by that same code.
const fs=require('fs'), vm=require('vm');
const html=fs.readFileSync(process.argv[2],'utf8');
const main=[...html.matchAll(/<script>([\s\S]*?)<\/script>/g)][1][1];
const cut=main.indexOf('/* ATOM-ENGINES BEGIN */');
if(cut<0) throw new Error('engine marker missing');
const physics=main.slice(0,cut);
const ctx={Math,console,Float64Array,Float32Array,Int8Array,Int16Array,Uint8Array,Object,Array,String,Number,JSON,isNaN};
vm.createContext(ctx);
vm.runInContext(physics+';this.ELEMENTS=ELEMENTS;this.bindingSEMF=bindingSEMF;this.BA_MEAS=BA_MEAS;this.valleyZ=valleyZ;this.USES=USES;',ctx);
if(ctx.ELEMENTS.length!==118||ctx.USES.length!==118) throw new Error('expected 118 elements');
const curve=[]; for(let A=4;A<=250;A+=2){ const z=ctx.valleyZ(A); curve.push([A,+(ctx.bindingSEMF(z,A)/A).toFixed(4)]); }
const meas=Object.keys(ctx.BA_MEAS).map(k=>{const p=k.split('-');return [+p[1],+ctx.BA_MEAS[k].toFixed(4),+p[0]];}).sort((a,b)=>a[0]-b[0]);
const out='/* GENERATED by scripts/sync-from-lab.sh from app/atom.html. Do not edit by hand. */\n'+physics+
  '\nvar BINDING={semf:'+JSON.stringify(curve)+',measured:'+JSON.stringify(meas)+'};\n';
fs.writeFileSync(process.argv[3],out);
console.log('physics',physics.length,'bytes; elements',ctx.ELEMENTS.length,'; binding points',curve.length);
